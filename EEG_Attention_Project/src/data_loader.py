"""Connect labeled trials to existing per-session NPZ EEG epochs.

The NPZ archives are generated by prepare_nm000275.py; source key 'X_B0_uV'
has shape (n_trials, 30, 500) and is already bandpassed/resampled.
Never concatenate all channels for all subjects unless enough RAM is available.
"""
from __future__ import annotations
from pathlib import Path
from collections.abc import Iterator, Sequence
import numpy as np
import pandas as pd


def read_labeled_table(csv_path: str | Path) -> pd.DataFrame:
    df = pd.read_csv(csv_path)
    needed = {'subject', 'session', 'trial_index', 'x_row', 'label', 'npz_file'}
    if not needed.issubset(df.columns):
        raise ValueError(f'Label file missing {sorted(needed - set(df.columns))}')
    df = df.loc[df.label.notna()].copy()
    df['label'] = df.label.astype('int64')
    df['x_row'] = df.x_row.astype('int64')
    if not df.label.isin([0, 1]).all() or df.x_row.lt(0).any():
        raise ValueError('Invalid labels or NPZ row numbers')
    if df.duplicated(['subject', 'session', 'trial_index']).any():
        raise ValueError('Duplicate event identities in labeled table')
    return df.reset_index(drop=True)


def select_fold_rows(labels: pd.DataFrame, folds: pd.DataFrame,
                     fold: int, role: str) -> pd.DataFrame:
    """Select a fixed fold role, e.g. train/val/test, WITHOUT epoch-level random split."""
    if role not in {'train', 'val', 'test'}:
        raise ValueError('role must be train, val or test')
    subjects = set(folds.loc[(folds.fold == fold) & (folds.role == role), 'subject'])
    if not subjects:
        raise ValueError(f'No subjects in fold={fold}, role={role}')
    return labels.loc[labels.subject.isin(subjects)].copy().reset_index(drop=True)


def iter_session_arrays(
    labels: pd.DataFrame,
    epochs_dir: str | Path,
    channels: Sequence[str] | str,
    source_key: str = 'X_B0_uV',
    expected_samples: int | None = 500,
) -> Iterator[tuple[np.ndarray, np.ndarray, pd.DataFrame]]:
    """Load ONE session at a time; verify x_row and trial_index alignment.

    Returns (X float32 [N,C,T], y int64 [N], metadata [N]); no scaling here.
    For E3 raw forehead source choose source_key='X_raw_FP_uV', channels=['FP1','FP2'],
    expected_samples=1000; sampling rate is then 500 Hz (not B0).
    """
    root = Path(epochs_dir)
    if labels.empty:
        raise ValueError('No labels selected')
    if 'npz_file' not in labels.columns or 'x_row' not in labels.columns:
        raise ValueError('Missing npz_file/x_row; read RT30 label CSV first')
    if isinstance(channels, str) and channels.lower() != 'all':
        raise ValueError('channels must be a list of names or "all"')
    for (subject, session), group in labels.groupby(['subject', 'session'], sort=True):
        files = group.npz_file.dropna().unique()
        if len(files) != 1:
            raise ValueError(f'{subject}/{session}: ambiguous npz file')
        filename = str(files[0])
        if Path(filename).name != filename:
            raise ValueError(f'Unsafe npz filename: {filename}')
        archive_path = root / filename
        if not archive_path.is_file():
            raise FileNotFoundError(f'Missing {archive_path}')
        with np.load(archive_path, allow_pickle=False) as data:
            if source_key not in data.files:
                raise KeyError(f'{archive_path}: no array {source_key}')
            name_key = 'forehead_names' if source_key == 'X_raw_FP_uV' else 'channel_names'
            if name_key not in data.files:
                raise KeyError(f'{archive_path}: missing {name_key}')
            available = [str(x).strip().upper() for x in data[name_key].tolist()]
            desired = available if channels == 'all' else [str(c).strip().upper() for c in channels]
            if len(set(desired)) != len(desired):
                raise ValueError(f'Duplicate requested channels: {desired}')
            missing = [c for c in desired if c not in available]
            if missing:
                raise ValueError(f'{archive_path}: missing channels {missing}')
            indices = [available.index(c) for c in desired]
            x_all = data[source_key]
            ix = group.x_row.to_numpy(dtype=np.int64)
            if ix.min() < 0 or ix.max() >= x_all.shape[0]:
                raise IndexError(f'{archive_path}: x_row out of range')
            if 'trial_index' not in data.files:
                raise KeyError(f'{archive_path}: no trial_index for alignment check')
            npz_trial_ids = data['trial_index'][ix]
            if not np.array_equal(npz_trial_ids, group.trial_index.to_numpy(dtype=np.int64)):
                raise ValueError(f'{archive_path}: CSV/NPZ trial_index mismatch')
            X = np.ascontiguousarray(x_all[ix][:, indices, :], dtype=np.float32)
            if expected_samples is not None and X.shape[-1] != expected_samples:
                raise ValueError(f'{archive_path}: expected {expected_samples} time points, got {X.shape[-1]}')
            if not np.isfinite(X).all():
                raise ValueError(f'{archive_path}: nonfinite EEG values')
        y = group.label.to_numpy(dtype=np.int64)
        if X.shape[0] != len(y):
            raise AssertionError('X/y length mismatch')
        yield X, y, group.reset_index(drop=True)


def load_arrays(labels: pd.DataFrame, epochs_dir: str | Path,
                channels: Sequence[str] | str,
                source_key: str = 'X_B0_uV',
                expected_samples: int | None = 500
                ) -> tuple[np.ndarray, np.ndarray, pd.DataFrame]:
    """Convenience for small experiments; FULL 30ch folds may need >1 GB RAM.

    To reduce peak memory use iter_session_arrays instead and make streaming datasets.
    """
    chunks = list(iter_session_arrays(labels, epochs_dir, channels, source_key, expected_samples))
    if not chunks:
        raise ValueError('No sessions found')
    return (np.concatenate([x for x, _, _ in chunks], axis=0),
            np.concatenate([y for _, y, _ in chunks], axis=0),
            pd.concat([meta for _, _, meta in chunks], ignore_index=True))


class EEGArrayDataset:
    """A simple torch-compatible, in-memory dataset for an individual fold."""
    def __init__(self, X: np.ndarray, y: np.ndarray):
        if X.ndim != 3 or len(X) != len(y):
            raise ValueError('Expected X (N,C,T), y (N,)')
        self.X = np.asarray(X, dtype=np.float32)
        self.y = np.asarray(y, dtype=np.float32)

    def __len__(self) -> int:
        return len(self.y)

    def __getitem__(self, idx: int):
        import torch
        return torch.from_numpy(self.X[idx].copy()), torch.tensor(self.y[idx], dtype=torch.float32)
